# 3편·4편 추가 시험: 기록 보존, 편 순서, 4회차 문항이 4편 빈칸에 걸리는지, 두 줄 제목 띠
import asyncio,json
from playwright.async_api import async_playwright
B='http://localhost:8765/insa-hoedok/'
SNAP="JSON.stringify({add:U.add,ov:U.ov,res:U.res,qres:U.qres})"
VIS="JSON.stringify(items('blanks').filter(b=>b.mine||b.core).map(b=>[b.id,b.rk,b.lp,b.r]))"
async def main():
    async with async_playwright() as p:
        b=await p.chromium.launch(executable_path='/usr/bin/google-chrome',args=['--no-sandbox'])
        ctx=await b.new_context(viewport={'width':1400,'height':1000}); page=await ctx.new_page()
        errs=[];page.on('pageerror',lambda e:errs.append(str(e)))
        page.on('dialog',lambda d:asyncio.ensure_future(d.accept()))
        await page.goto(B+'index.html#stay'); await page.wait_for_timeout(800)
        await page.set_input_files('#zipIn','/home/claude/test/test_r01.zip')
        await page.wait_for_selector('.pb button',timeout=60000); await page.click('.pb button'); await page.wait_for_timeout(800)
        await page.goto(B+'app.html'); await page.wait_for_timeout(4000)
        print('A rounds',await page.evaluate("D.rounds.map(r=>[r.key,r.start,r.n])"))
        snapA=await page.evaluate(SNAP); visA=json.loads(await page.evaluate(VIS))
        print('A visible mine/core',[v[:3] for v in visA])
        for z in ['교재_r04.zip','교재_r03.zip']:   # 일부러 4편을 먼저 넣는다
            await page.goto(B+'index.html#stay'); await page.wait_for_timeout(800)
            await page.set_input_files('#zipIn','/home/claude/test/'+z); await page.wait_for_timeout(9000)
        print('index rows',await page.evaluate("[...document.querySelectorAll('#ctRows .row')].map(r=>r.innerText.replace(/\\n/g,' '))"))
        await page.goto(B+'app.html'); await page.wait_for_timeout(6000)
        print('B rounds',await page.evaluate("D.rounds.map(r=>[r.key,r.part,r.start,r.n])"),'label',await page.inner_text('#rangeLbl'))
        snapB=await page.evaluate(SNAP); visB=json.loads(await page.evaluate(VIS))
        print('B record identical:',snapA==snapB)
        print('B visible mine/core',[v[:3] for v in visB])
        print('B blanks by q',await page.evaluate("JSON.stringify(D.blanks.filter(b=>/^r0[34]:/.test(b.id)).map(b=>b.q).reduce((a,q)=>(a[q]=(a[q]||0)+1,a),{}))"))
        print('B qspans by q',await page.evaluate("JSON.stringify(D.qspans.map(s=>s.q).reduce((a,q)=>(a[q]=(a[q]||0)+1,a),{}))"))
        print('B quiz',await page.evaluate("D.quiz.items.map(i=>qLbl(i.q)+'/'+i.key).join(', ')"))
        print('B heads r03/r04',await page.evaluate("[D.heads.filter(h=>h.id.startsWith('r03:')).length,D.heads.filter(h=>h.id.startsWith('r04:')).length]"))
        i101=await page.evaluate("D.pages.findIndex(p=>p.label==='101')")
        await page.evaluate(f"jumpTo({i101},0.35)"); await page.wait_for_timeout(1500)
        print('p101 bands',await page.evaluate(f"PG[{i101}].ov.querySelectorAll('.band').length"))
        await page.screenshot(path='/home/claude/test/s_p101.png')
        i128=await page.evaluate("D.pages.findIndex(p=>p.label==='128')")
        await page.evaluate(f"jumpTo({i128},0.7)"); await page.wait_for_timeout(1500); await page.screenshot(path='/home/claude/test/s_p128.png')
        await page.evaluate("BQ=3006;renderAll();updateSub()"); await page.wait_for_timeout(300)
        print('BQ 3006 (4회차 6번) blanks',await page.evaluate("items('blanks').filter(inBQ).map(b=>pageLabel(b.p)).join(',')"))
        await page.evaluate("BQ=0;renderAll();updateSub()")
        await page.evaluate("openQuiz()"); await page.wait_for_timeout(1200); await page.screenshot(path='/home/claude/test/s_quiz.png')
        await page.evaluate("openQuiz(3006)"); await page.wait_for_timeout(1200); await page.click('#sheet >> text=답 보기'); await page.wait_for_timeout(900); await page.screenshot(path='/home/claude/test/s_quiz6.png')
        await page.evaluate("$('#sheet').hidden=true")
        await page.evaluate("setSide('sc')"); await page.wait_for_timeout(600); await page.screenshot(path='/home/claude/test/s_sc.png')
        await page.evaluate("setSide('toc')")
        # 4편 쪽에 내 빈칸 만들기 → 새로고침 뒤 보존
        i150=await page.evaluate("D.pages.findIndex(p=>p.label==='150')")
        await page.evaluate("setMode('blank')"); await page.evaluate("setMK('mine')"); await page.wait_for_timeout(2500)
        await page.evaluate(f"jumpTo({i150},0.75)"); await page.wait_for_timeout(1500)
        pt=await page.evaluate(f"(()=>{{const w=wordsOf({i150}).find(w=>w[1]>0.8&&w[2]>0.05);const r=PG[{i150}].box.getBoundingClientRect();return [r.left+(w[0]+w[2]/2)*r.width,r.top+(w[1]+w[3]/2)*r.height]}})()")
        await page.mouse.click(pt[0],pt[1]); await page.wait_for_timeout(800)
        print('new mine:',await page.evaluate("JSON.stringify(U.add.blanks.slice(-1)[0])"))
        await page.evaluate("setMK(false)"); await page.wait_for_timeout(2500)
        await page.reload(); await page.wait_for_timeout(6000)
        print('reload mine/core',await page.evaluate("items('blanks').filter(b=>b.mine||b.core).map(b=>b.rk+':'+b.lp).join(',')"))
        print('errors',errs)
        await b.close()
asyncio.run(main())
